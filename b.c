int main() {
    int x = 10;
    print("Valoarea initiala a lui x:\n");
    print(x);
    
    // Reatribuire simplă
    x = 50;
    print("Valoarea lui x dupa atribuire:\n");
    print(x);
    
    // Reatribuire cu expresie (x = x + 15)
    x = x + 15;
    print("Valoarea lui x dupa x = x + 15:\n");
    print(x);
}